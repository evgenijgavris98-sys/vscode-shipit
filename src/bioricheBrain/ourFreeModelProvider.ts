import type { AgentRequest, BrainAgent, BrainProvider } from "./types";
import type { BrainConfig } from "./config";
import { loadAgentSkillInstructions } from "./skillLoader";

function assertSafeBaseUrl(value: string): URL {
  const url = new URL(value);
  if (url.username || url.password) throw new Error("Our Free Model base URL must not contain embedded credentials.");
  const isLoopback = url.hostname === "127.0.0.1" || url.hostname === "localhost" || url.hostname === "[::1]";
  if (url.protocol !== "https:" && !(url.protocol === "http:" && isLoopback)) {
    throw new Error("Our Free Model gateway must use HTTPS, or HTTP on loopback only.");
  }
  return url;
}

function endpoint(base: URL, path: string): string {
  return `${base.toString().replace(/\/$/, "")}/${path.replace(/^\//, "")}`;
}

interface ModelList {
  data?: Array<{ id?: string }>;
}

interface ChatCompletion {
  choices?: Array<{ message?: { content?: string | Array<{ type?: string; text?: string }> | null } }>;
  error?: { message?: string };
}

export class OurFreeModelProvider implements BrainProvider {
  public constructor(private readonly config: BrainConfig) {}

  public async run(agent: BrainAgent, request: AgentRequest): Promise<string> {
    if (!this.config.ourFreeModelApiKey) {
      throw new Error("Set OUR_FREE_MODEL_API_KEY to the local gateway key generated by Our Free Model.");
    }

    const base = assertSafeBaseUrl(this.config.ourFreeModelBaseUrl);
    const headers = {
      Authorization: `Bearer ${this.config.ourFreeModelApiKey}`,
      "Content-Type": "application/json",
    };
    const modelsResponse = await fetch(endpoint(base, "models"), {
      headers,
      signal: AbortSignal.timeout(15_000),
    });
    if (!modelsResponse.ok) {
      throw new Error(`Our Free Model model-list request failed (${modelsResponse.status}). Check that the local service is running and the API key is correct.`);
    }
    const modelList = await modelsResponse.json() as ModelList;
    const available = (modelList.data ?? []).map((item) => item.id).filter((id): id is string => Boolean(id));
    const model = this.config.ourFreeModelModel || available[0];
    if (!model) throw new Error("Our Free Model returned no available models. Refresh its model catalogue and check upstream connectivity.");
    if (this.config.ourFreeModelModel && available.length > 0 && !available.includes(this.config.ourFreeModelModel)) {
      throw new Error(`Configured OUR_FREE_MODEL_MODEL "${this.config.ourFreeModelModel}" is not in the gateway model list.`);
    }

    const role = [
      `You are ${agent.toUpperCase()} for BIORICHEBRAIN.`,
      "Work only within the assigned task. Distinguish sourced facts, supplier claims, hypotheses and validated results.",
      "Do not invent data, approvals or experimental outcomes. Avoid medical claims.",
      "Escalate safety, legal, regulatory, privacy and irreversible actions for human review.",
      await loadAgentSkillInstructions(agent),
    ].filter(Boolean).join("\n\n");
    const userContent = request.qaFeedback
      ? `${request.task.input}\n\nQA feedback:\n${request.qaFeedback}`
      : request.task.input;

    const response = await fetch(endpoint(base, "chat/completions"), {
      method: "POST",
      headers,
      body: JSON.stringify({
        model,
        messages: [
          { role: "system", content: role },
          { role: "user", content: userContent },
        ],
        max_tokens: 8192,
        stream: false,
      }),
      signal: AbortSignal.timeout(120_000),
    });
    if (!response.ok) {
      const body = await response.text();
      throw new Error(`Our Free Model inference failed (${response.status}): ${body.slice(0, 500)}`);
    }
    const payload = await response.json() as ChatCompletion;
    const content = payload.choices?.[0]?.message?.content;
    const output = typeof content === "string"
      ? content.trim()
      : Array.isArray(content)
        ? content.filter((part) => part.type === "text" && typeof part.text === "string").map((part) => part.text).join("\n").trim()
        : "";
    if (!output) throw new Error(payload.error?.message || "Our Free Model returned no text output.");
    return output;
  }
}
